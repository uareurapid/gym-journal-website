PAGES = [
    {
        "key": "PRIVACY_BODY",
        "filename": "privacy.html",
        "title": "Privacy Policy",
        "description": "Gym Journal does not collect any information when you download and use it. No account, no ads, no third parties.",
    },
    {
        "key": "TERMS_BODY",
        "filename": "terms.html",
        "title": "Terms of Use",
        "description": "The terms and conditions that apply to the Gym Journal app for iPhone and iPad.",
    },
]


def main() -> None:
    source = SRC.read_text(encoding="utf-8")

    for page in PAGES:
        raw = extract(page["key"], source)
        rendered = PAGE.format(
            title=page["title"],
            description=page["description"],
            body=body_html(raw),
            filename=page["filename"],
            site=SITE,
            app_store=APP_STORE,
        )
        target = OUT / page["filename"]
        target.write_text(rendered, encoding="utf-8")
        print(f"wrote {target.name} ({len(rendered)} bytes)")


if __name__ == "__main__":
    main()
