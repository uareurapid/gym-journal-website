#!/usr/bin/env python3
"""Generate privacy.html and terms.html for the Gym Journal site.

The body text is taken verbatim from the app's own source of truth,
`gym-journal/src/lib/legal.ts` — the same string the in-app Legal sheet renders.
This script only adds markup around the text; it never rewrites a word of it, so
the website, the in-app modal and the App Store listing cannot drift apart.

    python3 build_legal.py
"""

import html
import pathlib
import re

SRC = pathlib.Path(
    "/Users/paulocristo/workspace/mines/gym-journal/src/lib/legal.ts"
)
OUT = pathlib.Path(__file__).resolve().parent
SITE = "https://pcristo.dev/gym-journal-website"
APP_STORE = "https://apps.apple.com/us/app/gym-journal-sets-reps-log/id6817376632"


def extract(name: str, source: str) -> str:
    """Pull one exported template literal out of legal.ts, backticks and all."""
    match = re.search(rf"export const {name} = `(.*?)`;", source, re.S)
    if not match:
        raise SystemExit(f"could not find {name} in {SRC}")
    return match.group(1)


def escape(text: str) -> str:
    """Escape for HTML, then linkify the support address without changing it."""
    out = html.escape(text, quote=False)
    # The final label deliberately excludes a trailing dot: "…@me.com." at the
    # end of a sentence must not end up inside the href.
    return re.sub(
        r"([\w.+-]+@[\w-]+(?:\.[\w-]+)*)",
        r'<a href="mailto:\1">\1</a>',
        out,
    )


def body_html(raw: str) -> str:
    """Turn the app's plain-text body into paragraphs and headings.

    The text is one shared body across the author's apps and is deliberately not
    restructured, so headings are inferred from shape alone: a short block with
    no closing full stop, or a question. Blocks that merely open a paragraph
    ("This policy…", "These terms…") are prose and must stay prose.
    """
    blocks = [b.strip() for b in raw.split("\n\n") if b.strip()]
    parts: list[str] = []

    for block in blocks:
        line = " ".join(block.split())

        if re.search(r"generated by App Privacy Policy Generator", line, re.I):
            parts.append(f'      <p class="legal__credit">{escape(line)}</p>')
            continue

        opens_a_sentence = re.match(
            r"^(This|These|The|Upon|In|If|Similarly|Please|Since)\b", line
        )
        looks_like_heading = (
            len(line) <= 80 and not line.endswith(".")
        ) or (line.endswith("?") and len(line) <= 120)

        if looks_like_heading and not opens_a_sentence:
            parts.append(f"      <h2>{escape(line)}</h2>")
        else:
            parts.append(f"      <p>{escape(line)}</p>")

    return "\n".join(parts)


